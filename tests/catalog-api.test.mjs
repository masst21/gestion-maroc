import assert from 'node:assert/strict';
const base='http://127.0.0.1:3100';
async function login(email) {
 const r=await fetch(base+'/api/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({email,password:'Synthetic-test-password-123!'})});
 assert.equal(r.status,200);
 const cookie=r.headers.get('set-cookie')||'';
 assert.match(cookie,/HttpOnly/i);
 assert.match(cookie,/SameSite=Lax/i);
 const token=cookie.match(/gm_session=([a-f0-9]{64})/)?.[1];
 assert.ok(token);
 return token;
}
const sessions={'test-admin':await login('catalog-test@example.invalid'),'test-admin-other':await login('catalog-other@example.invalid')};
async function request(path,{method='GET',body,session='test-admin'}={}){
  const r=await fetch(base+path,{method,headers:{...(session?{cookie:'gm_session='+(sessions[session]||session)}:{}),...(body?{'content-type':'application/json'}:{})},...(body?{body:JSON.stringify(body)}:{})});
  const data=await r.json();
  return {status:r.status,data};
}
