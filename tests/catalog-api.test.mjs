import assert from 'node:assert/strict';
const base='http://127.0.0.1:3100';
async function request(path,{method='GET',body,session='test-admin'}={}){
  const r=await fetch(base+path,{method,headers:{...(session?{cookie:'gm_session='+session}:{}),...(body?{'content-type':'application/json'}:{})},...(body?{body:JSON.stringify(body)}:{})});
  const data=await r.json();
  return {status:r.status,data};
}
assert.equal((await request('/api/articles',{session:null})).status,401);
assert.equal((await request('/api/clients',{session:null})).status,403);
let r=await request('/api/articles');
assert.equal(r.status,200);
assert.ok(r.data.some(a=>a.reference==='LEGACY'&&a.stockQty===5));
const article={reference:'SCANNED-TEST',name:'Synthetic scan',barcode:'001234567890',salePriceHt:25,vatRate:0,stockQty:2,imageUrl:'data:image/jpeg;base64,/9j/2Q=='};
r=await request('/api/articles',{method:'POST',body:article});
assert.equal(r.status,201);
assert.equal(r.data.barcode,article.barcode);
assert.equal(r.data.imageUrl,article.imageUrl);
assert.equal(r.data.vatRate,0);
assert.equal((await request('/api/articles',{method:'POST',body:article})).status,409);
assert.equal((await request('/api/articles',{method:'POST',body:{...article,reference:'NEG',stockQty:-1}})).status,400);
r=await request('/api/articles',{session:'test-admin-other'});
assert.equal(r.status,200);
assert.ok(!r.data.some(a=>a.reference===article.reference));
r=await request('/api/clients');
assert.equal(r.status,200);
assert.ok(r.data.some(c=>c.id==='test-client'));
assert.ok(r.data.every(c=>!('cin' in c)&&!('address' in c)));
r=await request('/api/clients?id=test-client');
assert.equal(r.status,200);
assert.equal(r.data.cin,'AB123456');
assert.equal(r.data.balance,250);
assert.equal((await request('/api/clients?id=test-client',{session:'test-admin-other'})).status,404);
r=await request('/api/clients',{method:'POST',body:{name:'Synthetic new client',cin:'cd-123456',address:'Synthetic address',creditLimit:100}});
assert.equal(r.status,201);
const id=r.data.id;
assert.equal((await request('/api/clients',{method:'POST',body:{name:'Duplicate',cin:'CD123456'}})).status,409);
assert.equal((await request('/api/clients',{method:'PATCH',session:'test-admin-other',body:{id,name:'Unauthorized change'}})).status,404);
assert.equal((await request('/api/clients',{method:'PATCH',body:{id,name:'Synthetic updated',cin:'CD123456',address:'New synthetic address'}})).status,200);
r=await request('/api/clients?id='+id);
assert.equal(r.status,200);
assert.equal(r.data.address,'New synthetic address');
assert.equal(r.data.name,'Synthetic updated');
console.log('Article and client API smoke tests passed');
